PIPELINE_DESIGN = [
    ("Cheap checks first",
     "The checks run from cheapest to most expensive: schema and size (microseconds), then characters and language (milliseconds), then the AI models (about 0.15 to 0.8 s). Most bad requests never reach the expensive ones."),
    ("The first stop ends the trip",
     "The first REJECT, BLOCK, REDIRECT or ERROR stops the pipeline. Llama Guard is never called for a request that is already blocked."),
    ("Fail closed",
     "If any check throws an error or times out, the result is ERROR 503. A broken checker never lets a request through unchecked."),
    ("Two versions of the text",
     "After PII Detection there is an original and a masked version. Checks inside the process read the original. Anything that leaves the process, such as Llama Guard and the RAG pipeline, gets the masked one."),
    ("One decision, one JSON",
     "All results become one decision (CONTINUE, MASK, REDIRECT, REJECT, BLOCK, ERROR) with one HTTP status. FastAPI and Django share the same Python package, so the rules are identical."),
    ("Log decisions, never text",
     "One log line per request: request ID, each step's result, scores and entity types. The user's text is never logged, and blocked users are not told which check fired."),
]

